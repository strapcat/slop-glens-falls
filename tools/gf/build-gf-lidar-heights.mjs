// tools/gf/build-gf-lidar-heights.mjs — writes js/gf-lidar-heights.js from tools/gf/data/gf_lidar_heights.json
// usage: node tools/gf/build-gf-lidar-heights.mjs [out.js]   (GF_DATA=<dir> reads the JSON from another folder)
//
// Input: building heights Dave measured per OSM footprint from USGS 3DEP airborne LiDAR (NY_Hudson_D22, flown leaf-off
// 8 Nov 2022 - 15 Apr 2023), one [height_m, flag] per GF building id; the JSON's "rules" block says which flags are
// usable (ok, reviewed) and why the others are not. Output: GF_LIDAR_HEIGHTS, the usable heights only, in
// GF_BUILDINGS order. js/gf-building-heights.js applies them at run time to a copy of GF_BUILDINGS (src 4) wherever
// CC-003 used its default rule; js/gf-buildings.js is not touched. The output depends only on the JSON and
// GF_BUILDINGS.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { GF_BUILDINGS } from '../../js/gf-buildings.js';

const DATA = process.env.GF_DATA || fileURLToPath(new URL('data/', import.meta.url));
const OUT = process.argv[2] || fileURLToPath(new URL('../../js/gf-lidar-heights.js', import.meta.url));
const log = (...a) => console.log('[gf-lidar-heights]', ...a);

export const SRC_LIDAR = 4; // GF_BUILDINGS src: 0 height tag, 1 levels, 2 default rule; (CC-004: 3 landmark); 4 LiDAR
export const SRC_LABEL = 'lidar 2022-23';
const USE = ['ok', 'reviewed'];
const MIN_H = 2.0;
const MAX_H = 60;

// { heights: [[osm, height], ...] (usable only, GF_BUILDINGS order), counts, unmatched, onOsmHeights } of the document
export function buildGfLidarHeights(doc, buildingsData, sha256) {
  if (!doc || typeof doc.heights !== 'object' || !doc.rules || !doc.meta) throw new Error('gf_lidar_heights.json: no meta, rules or heights');
  const { rules, meta } = doc;
  if (JSON.stringify(rules.use) !== JSON.stringify(USE)) throw new Error(`rules.use is ${JSON.stringify(rules.use)}, not ${JSON.stringify(USE)}`);
  if (!rules.flags || typeof rules.flags !== 'object') throw new Error('rules.flags missing');
  if (meta.osm?.osmBase !== buildingsData.osmBase) throw new Error(`meta.osm.osmBase ${JSON.stringify(meta.osm?.osmBase)} is not GF_BUILDINGS.osmBase ${JSON.stringify(buildingsData.osmBase)}`);
  if (JSON.stringify(doc.fields) !== JSON.stringify(['height_m', 'flag'])) throw new Error(`fields ${JSON.stringify(doc.fields)} are not ["height_m", "flag"]`);
  const at = Object.fromEntries(buildingsData.fields.map((f, i) => [f, i]));
  const rows = new Map(buildingsData.buildings.map((r) => [r[at.osm], r]));

  // JSON.parse keeps only the last of two equal keys: look for duplicates in the raw text when we have it
  const keys = Object.keys(doc.heights);
  if (doc.rawKeys) {
    const seen = new Set();
    for (const k of doc.rawKeys) {
      if (seen.has(k)) throw new Error(`duplicate key ${k}`);
      seen.add(k);
    }
  }
  const flags = Object.fromEntries(Object.keys(rules.flags).map((f) => [f, 0]));
  const usable = new Map();
  for (const k of keys) {
    if (!rows.has(k)) throw new Error(`unknown OSM id ${k}`);
    const entry = doc.heights[k];
    if (!Array.isArray(entry) || entry.length !== 2) throw new Error(`${k}: expected [height_m, flag], got ${JSON.stringify(entry)}`);
    const [h, flag] = entry;
    if (!Object.hasOwn(rules.flags, flag)) throw new Error(`${k}: unknown flag ${JSON.stringify(flag)}`);
    flags[flag]++;
    if (!USE.includes(flag)) continue;
    if (!Number.isFinite(h) || h < MIN_H || h > MAX_H) throw new Error(`${k}: usable height ${JSON.stringify(h)} m outside ${MIN_H}-${MAX_H} m`);
    usable.set(k, h);
  }
  for (const u of doc.unmatched || []) {
    if (!rows.has(u.osm)) throw new Error(`unmatched entry: unknown OSM id ${u.osm}`);
    if (Object.hasOwn(doc.heights, u.osm)) throw new Error(`${u.osm} is both measured and unmatched`);
  }
  // in GF_BUILDINGS order (ways, then relations, by id)
  const heights = buildingsData.buildings.filter((r) => usable.has(r[at.osm])).map((r) => [r[at.osm], usable.get(r[at.osm])]);
  const onOsmHeights = heights.filter(([k]) => rows.get(k)[at.src] !== 2).map(([k]) => k);
  return {
    sha256,
    heights,
    counts: { matched: keys.length, usable: heights.length, flags },
    unmatched: (doc.unmatched || []).map((u) => u.osm),
    onOsmHeights
  };
}

export function serialize(doc, result) {
  const m = doc.meta;
  return [
    '// js/gf-lidar-heights.js — GENERATED by tools/gf/build-gf-lidar-heights.mjs, do not edit by hand.',
    '// Glens Falls building heights measured from USGS 3DEP airborne LiDAR (tools/gf/data/gf_lidar_heights.json): the',
    '// usable values only (flags ok and reviewed), one [OSM id, height in metres] per building, in GF_BUILDINGS order.',
    '// js/gf-building-heights.js applies them (src 4) where CC-003 used its default rule. Heights are as flown in',
    '// 2022-23, not 1993.',
    `// ${m.credit}; building ids ${m.osm.attribution.replace(/^Building ids and footprints /, '')}`,
    'export const GF_LIDAR_HEIGHTS = {',
    `  source: 'tools/gf/data/gf_lidar_heights.json',`,
    `  sha256: ${JSON.stringify(result.sha256)},`,
    `  srcCode: ${SRC_LIDAR},`,
    `  srcLabel: ${JSON.stringify(SRC_LABEL)},`,
    `  dataset: ${JSON.stringify(m.dataset)},`,
    `  collected: ${JSON.stringify({ start: m.collected.start, end: m.collected.end })},`,
    `  method: ${JSON.stringify(m.method)},`,
    `  credit: ${JSON.stringify(m.credit)},`,
    `  licence: ${JSON.stringify(m.licence)},`,
    `  osmBase: ${JSON.stringify(m.osm.osmBase)},`,
    `  counts: ${JSON.stringify(result.counts)},`,
    `  heights: [\n${result.heights.map((h) => `    ${JSON.stringify(h)}`).join(',\n')}\n  ]`,
    '};',
    ''
  ].join('\n');
}

function main() {
  const bytes = fs.readFileSync(path.join(DATA, 'gf_lidar_heights.json'));
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  const text = bytes.toString('utf8');
  const doc = JSON.parse(text);
  // the keys of "heights" as written, so a duplicate (which JSON.parse would silently drop) fails
  const block = text.slice(text.indexOf('"heights"'));
  doc.rawKeys = [...block.matchAll(/"([wr]\d+)"\s*:\s*\[/g)].map((x) => x[1]);
  const result = buildGfLidarHeights(doc, GF_BUILDINGS, sha256);
  const out = serialize(doc, result);
  fs.writeFileSync(OUT, out);

  const { counts } = result;
  log(`sha256 ${sha256}`);
  log(`matched ${counts.matched} of ${GF_BUILDINGS.buildings.length} GF buildings; unmatched ${result.unmatched.length}: ${(doc.unmatched || []).map((u) => `${u.osm} (${u.reason.split(';')[0]})`).join(', ')}`);
  log(`flags: ${Object.entries(counts.flags).map(([f, n]) => `${f} ${n}`).join(', ')}`);
  log(`usable (${USE.join(', ')}): ${counts.usable}; of them on buildings with an OSM height or levels (OSM wins, not applied): ${result.onOsmHeights.length}`);
  log(`applied as src ${SRC_LIDAR} (CC-003 default-rule buildings): ${counts.usable - result.onOsmHeights.length}`);
  if (doc.meta.counts && JSON.stringify(doc.meta.counts.flags) !== JSON.stringify(counts.flags)) log(`NOTE: meta.counts.flags ${JSON.stringify(doc.meta.counts.flags)} differ from the entries`);
  log(`wrote ${path.relative(process.cwd(), OUT)} (${(Buffer.byteLength(out) / 1024).toFixed(1)} KB)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
