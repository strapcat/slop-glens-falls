// tools/gf/build-gf-signals.mjs — writes js/gf-signals.js from tools/gf/data/osm_gf_signals.json
// usage: node tools/gf/build-gf-signals.mjs [out.js]        (GF_DATA=<dir> reads the raw JSON from another folder)
//
// Input (bash tools/gf/fetch.sh, q_gf_signals.overpassql): OSM nodes tagged highway=traffic_signals (signalled
// junctions) or crossing=traffic_signals (signalled pedestrian crossings) in the Glens Falls bbox.
// Output: GF_SIGNALS = { osmBase, attribution, junctions: [[x, z, osmId, direction|null], ...], crossings: [[x, z,
// osmId], ...] } in the GF_GEO frame (geo-frame.mjs, rounded to 0.1 m), each list sorted by OSM id. direction is the
// node's traffic_signals:direction (forward, backward or both), else null. Every point is an OSM node as it is: none is
// added, moved or dropped. The output depends only on the raw JSON.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LAT0, LON0, THETA, toLocal, q } from './geo-frame.mjs';
import { ATTRIBUTION } from './build-gf-geodata.mjs';
import { GF_GEO } from '../../js/gf-geodata.js';

const DATA = process.env.GF_DATA || fileURLToPath(new URL('data/', import.meta.url));
const OUT = process.argv[2] || fileURLToPath(new URL('../../js/gf-signals.js', import.meta.url));
const log = (...a) => console.log('[gf-signals]', ...a);

// The signals must land in the frame js/gf-geodata.js was built in
const { lat0, lon0, theta } = GF_GEO.frame;
if (lat0 !== LAT0 || lon0 !== LON0 || theta !== THETA) throw new Error('geo-frame.mjs and js/gf-geodata.js disagree on the frame');

const raw = JSON.parse(fs.readFileSync(path.join(DATA, 'osm_gf_signals.json'), 'utf8'));
if (!Array.isArray(raw.elements) || raw.remark) throw new Error('incomplete Overpass response for signals');
const nodes = raw.elements.filter((e) => e.type === 'node' && e.tags).sort((a, b) => a.id - b.id);
const at = (e) => toLocal(e.lon, e.lat).map(q);

const junctions = nodes
  .filter((e) => e.tags.highway === 'traffic_signals')
  .map((e) => [...at(e), e.id, e.tags['traffic_signals:direction'] || null]);
const crossings = nodes
  .filter((e) => e.tags.crossing === 'traffic_signals' && e.tags.highway !== 'traffic_signals')
  .map((e) => [...at(e), e.id]);
const osmBase = (raw.osm3s && raw.osm3s.timestamp_osm_base) || null;

const lines = [
  '// js/gf-signals.js — GENERATED by tools/gf/build-gf-signals.mjs, do not edit by hand.',
  '// Traffic signals in Glens Falls & South Glens Falls, in the GF_GEO frame (js/gf-geodata.js): junctions',
  '// (highway=traffic_signals) as [x, z, osmId, direction|null] and signalled pedestrian crossings',
  '// (crossing=traffic_signals) as [x, z, osmId], sorted by OSM id.',
  `// Data ${ATTRIBUTION}`,
  'export const GF_SIGNALS = {',
  `  osmBase: ${JSON.stringify(osmBase)},`,
  `  attribution: ${JSON.stringify(ATTRIBUTION)},`,
  `  junctions: [\n${junctions.map((j) => `    ${JSON.stringify(j)}`).join(',\n')}\n  ],`,
  `  crossings: [\n${crossings.map((c) => `    ${JSON.stringify(c)}`).join(',\n')}\n  ]`,
  '};',
  ''
];
fs.writeFileSync(OUT, lines.join('\n'));
log(`OSM base ${osmBase}: ${junctions.length} junction signals, ${crossings.length} signalled crossings -> ${path.relative(process.cwd(), OUT)}`);
