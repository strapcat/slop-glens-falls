// tools/gf/build-gf-bridges.mjs — writes js/gf-bridges.js: the OSM bridge, tunnel and layer tags GF_GEO's road graph does
// not carry, for the CC-005b decks (js/gf-surface.js)
// usage: node tools/gf/build-gf-bridges.mjs [out.js]
//
// Input: tools/gf/data/osm_gf_roads.json (the roads extract js/gf-geodata.js was built from) and GF_GEO. Every OSM way
// tagged bridge=yes is matched to the roadGraph link segments between its consecutive nodes (both ends equal at the
// geodata's 0.1 m rounding); a bridge way with a segment that matches no link stops the build. Ways tagged tunnel or a
// negative layer without a bridge are listed as at ground level: the bare-earth DEM is their road. Output: per bridge
// way its OSM id, name, highway, layer and the matched [link, segment] pairs. No height is stored: a deck's height comes
// from the terrain at its abutments (gf-surface.js), since a bare-earth DEM does not measure deck elevations.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { toLocal, q } from './geo-frame.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = process.argv[2] || path.join(HERE, '../../js/gf-bridges.js');
const log = (...a) => console.log('[gf-bridges]', ...a);

export function buildGfBridges(osm, geo) {
  const nodes = new Map(osm.elements.filter((e) => e.type === 'node').map((n) => [n.id, n]));
  const ways = osm.elements.filter((e) => e.type === 'way' && e.tags);
  const { nodes: gn, links, linkFields } = geo.roadGraph;
  const at = Object.fromEntries(linkFields.map((f, i) => [f, i]));
  const key = (x, z) => `${q(x)},${q(z)}`;
  const segs = new Map(); // "a|b" -> [link, segment] (either direction)
  links.forEach((l, li) => {
    const pts = [[gn[l[at.a] * 2], gn[l[at.a] * 2 + 1]]];
    const inner = l[at.pts] || [];
    for (let i = 0; i < inner.length; i += 2) pts.push([inner[i], inner[i + 1]]);
    pts.push([gn[l[at.b] * 2], gn[l[at.b] * 2 + 1]]);
    for (let s = 0; s + 1 < pts.length; s++) {
      segs.set(key(...pts[s]) + '|' + key(...pts[s + 1]), [li, s]);
      segs.set(key(...pts[s + 1]) + '|' + key(...pts[s]), [li, s]);
    }
  });
  const bridges = [], ground = [];
  for (const w of ways) {
    const t = w.tags;
    if (!t.highway) continue;
    const layer = t.layer !== undefined ? Number(t.layer) : null;
    if (t.bridge && t.bridge !== 'no') {
      const matched = [];
      for (let i = 0; i + 1 < w.nodes.length; i++) {
        const A = nodes.get(w.nodes[i]), B = nodes.get(w.nodes[i + 1]);
        if (!A || !B) throw new Error(`bridge way ${w.id}: node missing from the extract`);
        const m = segs.get(key(...toLocal(A.lon, A.lat)) + '|' + key(...toLocal(B.lon, B.lat)));
        if (!m) throw new Error(`bridge way ${w.id} (${t.name || t.highway}): segment ${i} matches no roadGraph link`);
        matched.push(m);
      }
      bridges.push({ osm: w.id, name: t.name || '', highway: t.highway, bridge: t.bridge, layer, segments: matched });
    } else if (t.tunnel && t.tunnel !== 'no' || (layer !== null && layer < 0)) {
      ground.push({ osm: w.id, name: t.name || '', highway: t.highway, tunnel: t.tunnel || '', layer });
    }
  }
  bridges.sort((a, b) => a.osm - b.osm);
  ground.sort((a, b) => a.osm - b.osm);
  return { bridges, ground };
}

function main() {
  const osm = JSON.parse(fs.readFileSync(path.join(HERE, 'data/osm_gf_roads.json'), 'utf8'));
  return import(pathToFileURL(path.join(HERE, '../../js/gf-geodata.js')).href).then(({ GF_GEO }) => {
    const { bridges, ground } = buildGfBridges(osm, GF_GEO);
    const out = [
      '// js/gf-bridges.js — GENERATED by tools/gf/build-gf-bridges.mjs, do not edit by hand.',
      '// The OSM bridge ways of tools/gf/data/osm_gf_roads.json on GF_GEO.roadGraph: each with the [link, segment] pairs',
      '// (roadGraph.links index, segment index along a -> pts -> b) it covers. No heights: a deck is held up by the terrain',
      '// at its abutments (js/gf-surface.js). `ground` lists the tunnel / negative-layer ways, whose road is the bare earth.',
      '// Data © OpenStreetMap contributors (ODbL 1.0), https://www.openstreetmap.org/copyright',
      'export const GF_BRIDGES = {',
      `  source: 'tools/gf/data/osm_gf_roads.json',`,
      '  bridges: [',
      bridges.map((b) => `    ${JSON.stringify(b)}`).join(',\n'),
      '  ],',
      '  ground: [',
      ground.map((g) => `    ${JSON.stringify(g)}`).join(',\n'),
      '  ]',
      '};',
      ''
    ].join('\n');
    fs.writeFileSync(OUT, out);
    log(`${bridges.length} bridge ways (${bridges.reduce((n, b) => n + b.segments.length, 0)} link segments), ${ground.length} ground-level tunnel / layer < 0 ways; wrote ${path.relative(process.cwd(), OUT)}`);
  });
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
