// tools/gf/build-gf-trees.mjs — writes js/gf-trees.js from tools/gf/data/gf_lidar_trees.json
// usage: node tools/gf/build-gf-trees.mjs [out.js]   (GF_DATA=<dir> reads the JSON from another folder)
//
// Input: canopy tops Dave detected in USGS 3DEP airborne LiDAR (NY_Hudson_D22, flown leaf-off 8 Nov 2022 -
// 15 Apr 2023), one [lon, lat, height_m, crown_r_m, flag] per top; the JSON's "rules" block says which flags are
// usable (ok) and why the others are not. Output: GF_TREES, the usable tops only, in JSON order, as a flat
// [x, z, h, r, ...] array in the GF_GEO frame (geo-frame.mjs, rounded to 0.1 m). No tree is added, moved, thinned or
// dropped here: js/gf-tree-placements.js turns them into renderer sites at run time. LiDAR measures position, height
// and spread only; it gives no species. The output depends only on the JSON.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { toLocal, q } from './geo-frame.mjs';

const DATA = process.env.GF_DATA || fileURLToPath(new URL('data/', import.meta.url));
const OUT = process.argv[2] || fileURLToPath(new URL('../../js/gf-trees.js', import.meta.url));
const log = (...a) => console.log('[gf-trees]', ...a);

const USE = ['ok'];
const FIELDS = ['lon', 'lat', 'height_m', 'crown_r_m', 'flag'];
const H_RANGE = [3.0, 40.0];
const R_RANGE = [1.5, 9.0];
const PER_LINE = 50; // trees per line of the output, for readable diffs

// { trees: [x, z, h, r, ...] (usable rows, JSON order), counts } of a gf_lidar_trees.json document
export function buildGfTrees(doc, sha256) {
  if (!doc || !Array.isArray(doc.trees) || !doc.rules || !doc.meta) throw new Error('gf_lidar_trees.json: no meta, rules or trees');
  const { rules, meta } = doc;
  if (JSON.stringify(rules.use) !== JSON.stringify(USE)) throw new Error(`rules.use is ${JSON.stringify(rules.use)}, not ${JSON.stringify(USE)}`);
  if (JSON.stringify(doc.fields) !== JSON.stringify(FIELDS)) throw new Error(`fields ${JSON.stringify(doc.fields)} are not ${JSON.stringify(FIELDS)}`);
  if (!rules.flags || typeof rules.flags !== 'object') throw new Error('rules.flags missing');
  const b = meta.bbox;
  if (!b || ![b.south, b.west, b.north, b.east].every(Number.isFinite)) throw new Error('meta.bbox missing or not numeric');

  const flags = Object.fromEntries(Object.keys(rules.flags).map((f) => [f, 0]));
  const seen = new Set();
  const trees = [];
  doc.trees.forEach((row, i) => {
    if (!Array.isArray(row) || row.length !== FIELDS.length) throw new Error(`row ${i}: expected ${FIELDS.length} fields, got ${JSON.stringify(row)}`);
    const [lon, lat, h, r, flag] = row;
    if (!Object.hasOwn(rules.flags, flag)) throw new Error(`row ${i}: unknown flag ${JSON.stringify(flag)}`);
    const key = `${lon},${lat}`;
    if (seen.has(key)) throw new Error(`row ${i}: a second row at lon/lat ${lon}, ${lat}`);
    seen.add(key);
    flags[flag]++;
    if (!USE.includes(flag)) return;
    if (!(lon >= b.west && lon <= b.east && lat >= b.south && lat <= b.north)) throw new Error(`row ${i}: usable tree at ${lon}, ${lat} outside meta.bbox`);
    if (!Number.isFinite(h) || h < H_RANGE[0] || h > H_RANGE[1]) throw new Error(`row ${i}: usable height ${JSON.stringify(h)} m outside ${H_RANGE[0]}-${H_RANGE[1]} m`);
    if (!Number.isFinite(r) || r < R_RANGE[0] || r > R_RANGE[1]) throw new Error(`row ${i}: usable crown radius ${JSON.stringify(r)} m outside ${R_RANGE[0]}-${R_RANGE[1]} m`);
    const [x, z] = toLocal(lon, lat).map(q);
    trees.push(x, z, h, r);
  });
  const counts = { candidates: doc.trees.length, usable: trees.length / 4, flags };
  const c = doc.counts || {};
  if (c.candidates !== counts.candidates) throw new Error(`counts.candidates ${c.candidates} does not match the ${counts.candidates} rows`);
  if (c.usable !== counts.usable) throw new Error(`counts.usable ${c.usable} does not match the ${counts.usable} usable rows`);
  for (const f of Object.keys(flags)) {
    if ((c.flags || {})[f] !== flags[f]) throw new Error(`counts.flags.${f} ${JSON.stringify((c.flags || {})[f])} does not match the ${flags[f]} rows`);
  }
  for (const f of Object.keys(c.flags || {})) if (!Object.hasOwn(flags, f)) throw new Error(`counts.flags.${f} is not a flag in rules.flags`);
  return { sha256, trees, counts };
}

export function serialize(doc, result) {
  const m = doc.meta;
  const rows = [];
  for (let i = 0; i < result.trees.length; i += PER_LINE * 4) rows.push(`    ${result.trees.slice(i, i + PER_LINE * 4).join(',')}`);
  return [
    '// js/gf-trees.js — GENERATED by tools/gf/build-gf-trees.mjs, do not edit by hand.',
    '// Glens Falls trees: canopy tops detected in USGS 3DEP airborne LiDAR (tools/gf/data/gf_lidar_trees.json), the usable',
    '// rows only (flag ok), in JSON order, as a flat [x, z, h, r, ...] array in the GF_GEO frame (x, z at 0.1 m; h the',
    '// height and r the crown radius in metres). Trees as flown in 2022-23 (leaf-off), not 1993. LiDAR gives no species.',
    `// ${m.credit}`,
    'export const GF_TREES = {',
    `  source: 'tools/gf/data/gf_lidar_trees.json',`,
    `  sha256: ${JSON.stringify(result.sha256)},`,
    `  dataset: ${JSON.stringify(m.dataset)},`,
    `  collected: ${JSON.stringify(m.collected)},`,
    `  credit: ${JSON.stringify(m.credit)},`,
    `  licence: ${JSON.stringify(m.licence)},`,
    `  method: ${JSON.stringify(m.method)},`,
    `  notSpecies: ${JSON.stringify(m.notSpecies)},`,
    `  counts: ${JSON.stringify(result.counts)},`,
    `  fields: ['x', 'z', 'h', 'r'],`,
    `  trees: [\n${rows.join(',\n')}\n  ]`,
    '};',
    ''
  ].join('\n');
}

function main() {
  const bytes = fs.readFileSync(path.join(DATA, 'gf_lidar_trees.json'));
  const sha256 = crypto.createHash('sha256').update(bytes).digest('hex');
  const doc = JSON.parse(bytes.toString('utf8'));
  const result = buildGfTrees(doc, sha256);
  const out = serialize(doc, result);
  fs.writeFileSync(OUT, out);
  const { counts } = result;
  log(`sha256 ${sha256}`);
  log(`candidates ${counts.candidates}; usable (${USE.join(', ')}) ${counts.usable}`);
  log(`flags: ${Object.entries(counts.flags).map(([f, n]) => `${f} ${n}`).join(', ')}`);
  const hs = [], rs = [];
  for (let i = 0; i < result.trees.length; i += 4) { hs.push(result.trees[i + 2]); rs.push(result.trees[i + 3]); }
  const pct = (a, p) => { const s = a.slice().sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(p * s.length))]; };
  log(`heights p5 ${pct(hs, 0.05)}, median ${pct(hs, 0.5)}, p95 ${pct(hs, 0.95)}, max ${Math.max(...hs)} m; crown radius p5 ${pct(rs, 0.05)}, median ${pct(rs, 0.5)}, p95 ${pct(rs, 0.95)}, max ${Math.max(...rs)} m`);
  log(`wrote ${path.relative(process.cwd(), OUT)} (${(Buffer.byteLength(out) / 1024).toFixed(1)} KB)`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) main();
