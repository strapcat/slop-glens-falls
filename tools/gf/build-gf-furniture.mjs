// tools/gf/build-gf-furniture.mjs — writes js/gf-furniture.js from tools/gf/data/osm_gf_street_furniture.json
// usage: node tools/gf/build-gf-furniture.mjs [out.js]        (GF_DATA=<dir> reads the raw JSON from another folder)
//
// CC-006. Input (bash tools/gf/fetch.sh, q_gf_street_furniture.overpassql): OSM nodes in the Glens Falls bbox tagged
// highway=stop, traffic_sign=stop, highway=give_way, highway=crossing or crossing=*, and highway=street_lamp. Modern OSM
// (its osmBase), not 1993. Output: GF_FURNITURE = { osmBase, attribution, stops, giveWays, crossings, lamps, counts },
// each list sorted by OSM id, in the GF_GEO frame (geo-frame.mjs, rounded to 0.1 m):
//   stops      [x, z, osmId, all (1: stop=all), direction | null]  highway=stop, and traffic_sign=stop nodes that are
//              not also highway=stop (one stop each)
//   giveWays   [x, z, osmId]                                       highway=give_way (a yield, not a stop: no sign)
//   crossings  [x, z, osmId, kind]                                 MARKED crossings only: crossing=marked|zebra, or
//              crossing:markings / crossing_ref zebra|ladder|yes|lines|dashes|... (not "no"); kind is the value that
//              qualified it. crossing=traffic_signals nodes are js/gf-signals.js's; unmarked, uncontrolled-without-
//              markings and informal crossings are counted, not kept.
//   lamps      [x, z, osmId]                                       highway=street_lamp
// Every point is an OSM node as it is: none is added, moved or dropped, other than by the rules above.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LAT0, LON0, THETA, toLocal, q } from './geo-frame.mjs';
import { ATTRIBUTION } from './build-gf-geodata.mjs';

const DATA = process.env.GF_DATA || fileURLToPath(new URL('data/', import.meta.url));
const OUT = process.argv[2] || fileURLToPath(new URL('../../js/gf-furniture.js', import.meta.url));
const log = (...a) => console.log('[gf-furniture]', ...a);

const MARKED = new Set(['marked', 'zebra']);
const MARKINGS_NO = new Set(['no', 'none']);

export function buildGfFurniture(raw) {
  if (!Array.isArray(raw.elements) || raw.remark) throw new Error('incomplete Overpass response for street furniture');
  const nodes = raw.elements.filter((e) => e.type === 'node' && e.tags).sort((a, b) => a.id - b.id);
  const at = (e) => toLocal(e.lon, e.lat).map(q);
  const stops = [], giveWays = [], crossings = [], lamps = [];
  const counts = { nodes: nodes.length, highwayStop: 0, trafficSignStopOnly: 0, stopAll: 0, giveWay: 0, crossingNodes: 0, crossingKinds: {}, marked: 0, signalCrossings: 0, lamps: 0 };
  for (const e of nodes) {
    const t = e.tags;
    const [x, z] = at(e);
    const hwStop = t.highway === 'stop';
    const signStop = !hwStop && t.traffic_sign === 'stop';
    if (hwStop || signStop) {
      stops.push([x, z, e.id, t.stop === 'all' ? 1 : 0, t.direction || null]);
      if (hwStop) counts.highwayStop++; else counts.trafficSignStopOnly++;
      if (t.stop === 'all') counts.stopAll++;
    }
    if (t.highway === 'give_way') { giveWays.push([x, z, e.id]); counts.giveWay++; }
    if (t.highway === 'crossing' || t.crossing) {
      counts.crossingNodes++;
      const kind = t.crossing || '(untagged)';
      counts.crossingKinds[kind] = (counts.crossingKinds[kind] || 0) + 1;
      if (t.crossing === 'traffic_signals') counts.signalCrossings++;
      else {
        const markings = t['crossing:markings'] || t.crossing_ref || null;
        const why = MARKED.has(t.crossing) ? t.crossing : markings && !MARKINGS_NO.has(markings) ? `markings=${markings}` : null;
        if (why) { crossings.push([x, z, e.id, why]); counts.marked++; }
      }
    }
    if (t.highway === 'street_lamp') { lamps.push([x, z, e.id]); counts.lamps++; }
  }
  return {
    frame: { lat0: LAT0, lon0: LON0, theta: THETA },
    osmBase: (raw.osm3s && raw.osm3s.timestamp_osm_base) || null,
    stops, giveWays, crossings, lamps, counts,
    attribution: ATTRIBUTION
  };
}

export function moduleText(d) {
  const list = (a) => `[\n${a.map((r) => '    ' + JSON.stringify(r)).join(',\n')}\n  ]`;
  return [
    '// js/gf-furniture.js — GENERATED by tools/gf/build-gf-furniture.mjs, do not edit by hand.',
    '// CC-006: OSM street furniture in the Glens Falls bbox (modern OSM at osmBase, not 1993), in the GF_GEO frame (0.1 m):',
    '// stops [x, z, osmId, all, direction], giveWays [x, z, osmId], crossings (marked only) [x, z, osmId, kind], lamps',
    '// [x, z, osmId]. See the generator for the rules.',
    `// Data ${ATTRIBUTION}`,
    'export const GF_FURNITURE = {',
    `  frame: ${JSON.stringify(d.frame)},`,
    `  osmBase: ${JSON.stringify(d.osmBase)},`,
    `  counts: ${JSON.stringify(d.counts)},`,
    `  stops: ${list(d.stops)},`,
    `  giveWays: ${list(d.giveWays)},`,
    `  crossings: ${list(d.crossings)},`,
    `  lamps: ${list(d.lamps)},`,
    `  attribution: ${JSON.stringify(d.attribution)}`,
    '};',
    ''
  ].join('\n');
}

function main() {
  const raw = JSON.parse(fs.readFileSync(path.join(DATA, 'osm_gf_street_furniture.json'), 'utf8'));
  const d = buildGfFurniture(raw);
  fs.writeFileSync(OUT, moduleText(d));
  log(`OSM base ${d.osmBase}; ${JSON.stringify(d.counts)}`);
  log(`wrote ${path.relative(process.cwd(), OUT)}`);
}

if (process.argv[1] && import.meta.url === new URL(`file://${path.resolve(process.argv[1])}`).href) main();
