test('placeholders change nothing; the unsourced features wait in pending; the six Dave-requested ids are accounted for', () => {
  const applied = new Set(GF_LANDMARKS.buildings.map((b) => b.osm));
  for (const l of doc.landmarks.filter((x) => x.status !== 'use')) {
    assert.ok(!applied.has(l.osm), `${l.id} (${l.status}) applied`);
    const i = base.records.findIndex((r) => r.osm === l.osm);
    assert.deepEqual(result.records[i], base.records[i], l.id);
  }
  const featureIds = GF_LANDMARKS.features.map((f) => f.id);
  assert.deepEqual(featureIds, ['civil-war-monument', 'first-presbyterian/spire']);
  const pending = (id, what) => GF_LANDMARKS.pending.some((p) => p.id === id && p.what.startsWith(what) && p.reason);
  assert.ok(pending('finch-pruyn-mill', 'smokestack'));
  assert.ok(pending('finch-pruyn-mill', 'woodpile'));
  assert.ok(pending('first-presbyterian', 'tower'));
  assert.ok(pending('church-of-the-messiah', 'tower'));
  assert.ok(!featureIds.some((id) => /tower|smokestack|woodpile/.test(id)));
  const dave = doc.landmarks.filter((l) => l.daveRequested).map((l) => l.id);
  assert.deepEqual(dave.sort(), ['civic-center', 'civil-war-monument', 'crandall-library', 'finch-pruyn-mill', 'sandys-clam-bar', 'talk-of-the-town']);
  for (const id of dave) {
    const done = GF_LANDMARKS.buildings.some((b) => b.id === id) || GF_LANDMARKS.features.some((f) => f.id === id);
    const waiting = GF_LANDMARKS.pending.some((p) => p.id === id && p.daveRequested && p.reason);
    assert.ok(done || waiting, id);
  }
  assert.ok(GF_LANDMARKS.pending.slice(0, 8).every((p) => p.daveRequested), 'Dave-requested first');
  assert.deepEqual(GF_LANDMARKS.flagged.map((f) => f.osm), ['w682532345', 'w120878979']);
});

test('the Civil War Monument: one 12.8 m obelisk at its node, clear of buildings and roads, a player collider only', () => {
  const mon = result.features.filter((f) => f.type === 'obelisk');
  assert.equal(mon.length, 1);
  const [m] = mon;
  assert.deepEqual([m.x, m.z, m.base, m.top, m.style], [-192.2, -167.4, 0, 12.8, 'stone']);
  for (const c of base.colliders) assert.ok(!polygonContains(c.polygon, m.x, m.z), 'inside a building');
  let nearest = Infinity;
  for (const l of driveLinks(GF_GEO)) {
    for (let k = 0; k + 1 < l.pts.length; k++) {
      const [ax, az] = l.pts[k], [bx, bz] = l.pts[k + 1];
      const ex = bx - ax, ez = bz - az, u = Math.max(0, Math.min(1, ((m.x - ax) * ex + (m.z - az) * ez) / (ex * ex + ez * ez)));
      nearest = Math.min(nearest, Math.hypot(ax + ex * u - m.x, az + ez * u - m.z));
    }
  }
  assert.ok(nearest >= 5, `${nearest.toFixed(1)} m from a drive link`);
  const extra = result.colliders.slice(base.colliders.length);
  assert.equal(extra.length, 1);
  assert.equal(extra[0].maxY, 12.8);
  assert.ok(polygonContains(extra[0].polygon, m.x, m.z));
  assert.equal(result.obstacles.length, base.obstacles.length, 'no pedestrian obstacle');
});

