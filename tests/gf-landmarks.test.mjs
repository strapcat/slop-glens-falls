test('gf-landmarks.js is regenerated byte for byte; applying it gives the same result every time', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gf-landmarks '));
  try {
    const out = path.join(dir, 'gf-landmarks.js');
    const run = spawnSync(process.execPath, [path.join(root, 'tools/gf/build-gf-landmarks.mjs'), out], { encoding: 'utf8' });
    assert.ifError(run.error);
    assert.equal(run.status, 0, run.stderr + run.stdout);
    assert.ok(fs.readFileSync(out).equals(fs.readFileSync(path.join(root, 'js/gf-landmarks.js'))), 'js/gf-landmarks.js is stale');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  assert.equal(JSON.stringify(applyGfLandmarks(createGfBuildingRecords(GF_BUILDINGS), GF_LANDMARKS)), JSON.stringify(result));
});

