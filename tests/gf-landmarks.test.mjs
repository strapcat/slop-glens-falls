test('shapes: every type spans exactly base to top; gable and hip only over a near-rectangular footprint', () => {
  const rect = { outer: [{ x: 0, z: 0 }, { x: 20, z: 3 }, { x: 18.5, z: 13 }, { x: -1.5, z: 10 }], holes: [] };
  const ell = { outer: [{ x: 0, z: 0 }, { x: 20, z: 0 }, { x: 20, z: 6 }, { x: 6, z: 6 }, { x: 6, z: 20 }, { x: 0, z: 20 }], holes: [] };
  const cases = [
    { type: 'spire', base: 21.3, top: 44.8 },
    { type: 'tower', base: 10, top: 23.8 },
    { type: 'clock-tower', base: 12, top: 30 },
    { type: 'dome', base: 15, top: 19 },
    { type: 'smokestack', base: 0, top: 60 },
    { type: 'gable', base: 7.2, top: 11, polygon: rect },
    { type: 'hip', base: 7.2, top: 11, polygon: rect },
    { type: 'obelisk', base: 0, top: 12.8 }
  ];
  for (const c of cases) {
    const g = meshes.featureGeometry({ id: c.type, x: 5, z: -3, ...c });
    assert.ok(!g.skipped, `${c.type} skipped: ${g.skipped}`);
    const ys = [...g.body, ...g.trim].filter((_, i) => i % 3 === 1);
    assert.ok([...g.body, ...g.trim].every(Number.isFinite), c.type);
    assert.ok(ys.length >= 9 && (g.body.length + g.trim.length) % 9 === 0, c.type);
    assert.ok(Math.abs(Math.max(...ys) - c.top) <= 0.01, `${c.type} top ${Math.max(...ys)}`);
    assert.ok(Math.abs(Math.min(...ys) - c.base) <= 0.01, `${c.type} base ${Math.min(...ys)}`);
  }
  assert.match(meshes.featureGeometry({ id: 'L', type: 'gable', x: 0, z: 0, base: 7, top: 10, polygon: ell }).skipped, /fills \d+% of its rectangle/);
  assert.match(meshes.featureGeometry({ id: 'L', type: 'hip', x: 0, z: 0, base: 7, top: 10, polygon: ell }).skipped, /under 90%/);
  // the monument as drawn: plinth, shaft, pyramidion and eagle make exactly its sourced 12.8 m
  const mon = result.features.find((f) => f.type === 'obelisk');
  const g = meshes.featureGeometry(mon);
  const ys = [...g.body, ...g.trim].filter((_, i) => i % 3 === 1);
  assert.equal(Math.max(...ys), 12.8);
  assert.equal(Math.min(...ys), 0);
});

