// A small document in the real schema: the first `n` rows of the real one, with consistent counts
function fixture(n, edit = () => {}) {
  const d = structuredClone({ ...doc, trees: doc.trees.slice(0, n) });
  const flags = Object.fromEntries(Object.keys(d.rules.flags).map((f) => [f, 0]));
  edit(d);
  for (const r of d.trees) if (Object.hasOwn(flags, r[4])) flags[r[4]]++;
  d.counts = d.counts?.keep ? d.counts.keep : { candidates: d.trees.length, usable: flags.ok, flags };
  return d;
}

test('the generator refuses malformed data, naming the row or value', () => {
  assert.equal(buildGfTrees(fixture(50), 'x').trees.length / 4, doc.trees.slice(0, 50).filter((r) => r[4] === 'ok').length);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.rules.use = ['ok', 'sparse']; }), 'x'), /rules\.use is \["ok","sparse"\]/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.fields = ['lon', 'lat', 'height_m', 'crown_r_m']; }), 'x'), /fields .* are not/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.trees[3][4] = 'shrub'; }), 'x'), /row 3: unknown flag "shrub"/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.trees[4] = [-73.7, 43.3, 12, 3, 'ok']; }), 'x'), /row 4: usable tree at -73\.7, 43\.3 outside meta\.bbox/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.trees[5][2] = 41; d.trees[5][4] = 'ok'; }), 'x'), /row 5: usable height 41 m outside 3-40 m/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.trees[5][2] = null; d.trees[5][4] = 'ok'; }), 'x'), /row 5: usable height null m/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.trees[6][3] = 9.5; d.trees[6][4] = 'ok'; }), 'x'), /row 6: usable crown radius 9\.5 m outside 1\.5-9 m/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.trees[7] = [...d.trees[2]]; }), 'x'), /row 7: a second row at lon\/lat/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.counts = { keep: { candidates: 51, usable: 0, flags: {} } }; }), 'x'), /counts\.candidates 51 does not match the 50 rows/);
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.counts = { keep: { ...structuredClone(fixture(50).counts), usable: 3 } }; }), 'x'), /counts\.usable 3 does not match/);
  const badFlags = structuredClone(fixture(50).counts);
  badFlags.flags.ok += 1;
  assert.throws(() => buildGfTrees(fixture(50, (d) => { d.counts = { keep: badFlags }; }), 'x'), /counts\.flags\.ok .* does not match/);
  // a flagged row may be out of range: it is never drawn
  assert.doesNotThrow(() => buildGfTrees(fixture(50, (d) => { d.trees[8] = [d.trees[8][0], d.trees[8][1], 45, 0.5, 'tall']; }), 'x'));
});

test('nothing invented: every site is a usable row where it was measured; no flagged row is drawn', () => {
  const key = (x, z) => `${x},${z}`;
  const usable = new Map();
  const flagged = new Set();
  for (const [lon, lat, h, r, flag] of doc.trees) {
    const [x, z] = toLocal(lon, lat).map(q);
    if (flag === 'ok') usable.set(key(x, z), [h, r]);
    else flagged.add(key(x, z));
  }
  assert.equal(usable.size, 77976, 'usable rows are distinct after rounding');
  for (let i = 0; i < GF_TREES.trees.length; i += 4) {
    const [x, z, h, r] = GF_TREES.trees.slice(i, i + 4);
    assert.deepEqual(usable.get(key(x, z)), [h, r], `GF_TREES row ${i / 4}`);
  }
  for (const s of plan.sites) {
    assert.ok(usable.has(key(s.x, s.z)), `site (${s.x}, ${s.z}) is not a usable row`);
    assert.ok(!flagged.has(key(s.x, s.z)), `site (${s.x}, ${s.z}) is a flagged row`);
  }
  assert.equal(new Set(plan.sites.map((s) => key(s.x, s.z))).size, plan.sites.length, 'one site per row');
});

// Distance from (x, z) to a flat ring's edges
function ringDistance(ring, x, z) {
  let best = Infinity;
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    const ax = ring[j], az = ring[j + 1], ex = ring[i] - ax, ez = ring[i + 1] - az;
    const len2 = ex * ex + ez * ez;
    const u = len2 ? Math.max(0, Math.min(1, ((x - ax) * ex + (z - az) * ez) / len2)) : 0;
    best = Math.min(best, Math.hypot(ax + ex * u - x, az + ez * u - z));
  }
  return best;
}
function inRing(ring, x, z) {
  let inside = false;
  for (let i = 0, j = ring.length - 2; i < ring.length; j = i, i += 2) {
    if ((ring[i + 1] > z) !== (ring[j + 1] > z) && x < ring[i] + ((ring[j] - ring[i]) * (z - ring[i + 1])) / (ring[j + 1] - ring[i + 1])) inside = !inside;
  }
  return inside;
}

test('placement rules: trunks clear of water, carriageways and walls; scale, spread and species as stated', () => {
  // GF_BUILDINGS footprints and road segments near each site, through 50 m grids
  const grid = new Map();
  const add = (minX, maxX, minZ, maxZ, item) => {
    for (let gx = Math.floor(minX / 50); gx <= Math.floor(maxX / 50); gx++) {
      for (let gz = Math.floor(minZ / 50); gz <= Math.floor(maxZ / 50); gz++) {
        const k = `${gx},${gz}`;
        if (!grid.has(k)) grid.set(k, []);
        grid.get(k).push(item);
      }
    }
  };
  const at = Object.fromEntries(GF_BUILDINGS.fields.map((f, i) => [f, i]));
  for (const row of GF_BUILDINGS.buildings) {
    const o = row[at.outer];
    const xs = o.filter((_, i) => i % 2 === 0), zs = o.filter((_, i) => i % 2 === 1);
    add(Math.min(...xs) - 1, Math.max(...xs) + 1, Math.min(...zs) - 1, Math.max(...zs) + 1, { kind: 'building', outer: o, holes: row[at.holes] });
  }
  const { nodes, links, linkFields } = GF_GEO.roadGraph;
  const lf = Object.fromEntries(linkFields.map((f, i) => [f, i]));
  for (const l of links) {
    const pts = [nodes[l[lf.a] * 2], nodes[l[lf.a] * 2 + 1], ...(l[lf.pts] || []), nodes[l[lf.b] * 2], nodes[l[lf.b] * 2 + 1]];
    const half = l[lf.width] / 2;
    for (let k = 0; k + 3 < pts.length; k += 2) {
      add(Math.min(pts[k], pts[k + 2]) - half - 1, Math.max(pts[k], pts[k + 2]) + half + 1, Math.min(pts[k + 1], pts[k + 3]) - half - 1, Math.max(pts[k + 1], pts[k + 3]) + half + 1,
        { kind: 'road', seg: pts.slice(k, k + 4), half });
    }
  }
  const rowAt = new Map();
  for (let k = 0; k < GF_TREES.trees.length; k += 4) rowAt.set(`${GF_TREES.trees[k]},${GF_TREES.trees[k + 1]}`, k);
  const water = GF_GEO.water.map((w) => {
    const xs = w.outer.filter((_, i) => i % 2 === 0), zs = w.outer.filter((_, i) => i % 2 === 1);
    return { ...w, minX: Math.min(...xs), maxX: Math.max(...xs), minZ: Math.min(...zs), maxZ: Math.max(...zs) };
  });
  let nearestWall = Infinity, nearestRoad = Infinity;
  for (const s of plan.sites) {
    for (const w of water) if (s.x >= w.minX && s.x <= w.maxX && s.z >= w.minZ && s.z <= w.maxZ) assert.ok(!(inRing(w.outer, s.x, s.z) && !(w.holes || []).some((h) => inRing(h, s.x, s.z))), `(${s.x}, ${s.z}) in water`);
    for (const it of grid.get(`${Math.floor(s.x / 50)},${Math.floor(s.z / 50)}`) || []) {
      if (it.kind === 'building') {
        assert.ok(!inRing(it.outer, s.x, s.z) || it.holes.some((h) => inRing(h, s.x, s.z)), `(${s.x}, ${s.z}) inside a building`);
        nearestWall = Math.min(nearestWall, ringDistance(it.outer, s.x, s.z));
      } else {
        const [ax, az, bx, bz] = it.seg, ex = bx - ax, ez = bz - az, len2 = ex * ex + ez * ez;
        const u = len2 ? Math.max(0, Math.min(1, ((s.x - ax) * ex + (s.z - az) * ez) / len2)) : 0;
        nearestRoad = Math.min(nearestRoad, Math.hypot(ax + ex * u - s.x, az + ez * u - s.z) - it.half);
      }
    }
    // scale and spread from the measured height and crown radius, the shape slot from the position
    const i = rowAt.get(`${s.x},${s.z}`);
    const h = GF_TREES.trees[i + 2], r = GF_TREES.trees[i + 3];
    const m = TREE_MODELS[s.species];
    assert.ok(Number.isInteger(s.species) && s.species >= 0 && s.species <= 2);
    assert.equal(s.species, speciesAt(s.x, s.z));
    assert.equal(s.scale, h / m.H);
    assert.equal(s.sx, Math.min(SPREAD[1], Math.max(SPREAD[0], r / (m.R * s.scale))));
    assert.equal(s.sz, s.sx);
    assert.deepEqual([s.y, s.tier], [0, TIER]);
  }
  assert.ok(nearestWall >= 0.9, `a trunk ${nearestWall.toFixed(2)} m from a wall`);
  assert.ok(nearestRoad >= 0.4, `a trunk ${nearestRoad.toFixed(2)} m outside a carriageway edge`);
  // trunk colliders: one small square per site
  plan.trunks.forEach((t, k) => {
    const s = plan.sites[k];
    const h = s.scale * TREE_MODELS[s.species].H;
    const half = Math.max(TRUNK.minHalf, TRUNK.halfPerM * h);
    assert.ok(Math.abs(t.maxX - t.minX - 2 * half) < 1e-9 && Math.abs((t.minX + t.maxX) / 2 - s.x) < 1e-9 && Math.abs((t.minZ + t.maxZ) / 2 - s.z) < 1e-9);
    assert.equal(t.minY, 0);
    assert.ok(Math.abs(t.maxY - Math.min(TRUNK.maxTop, TRUNK.topPerM * h)) < 1e-9);
    assert.equal(t.polygon.outer.length, 4);
  });
});

// The modules a file reaches through static imports (as tests/city-runtime.test.mjs walks them)
function staticGraph(entry) {
  const seen = new Set();
  const walk = (file) => {
    if (seen.has(file)) return;
    seen.add(file);
    const src = fs.readFileSync(path.join(root, 'js', file), 'utf8');
    for (const m of src.matchAll(/^\s*import\s+(?:[\w$*{][\s\S]*?\s+from\s+)?['"]([^'"]+)['"]/gm)) if (m[1].startsWith('./')) walk(m[1].slice(2));
  };
  walk(entry);
  return seen;
}

test('Glens Falls loads the shared renderer and its own tree data, never New York\'s', () => {
  const gf = staticGraph('gf-main.js');
  for (const f of ['trees.js', 'gf-trees.js', 'gf-tree-placements.js']) assert.ok(gf.has(f), f);
  for (const f of ['tree-geodata.js', 'tree-placements.js', 'street-details.js']) assert.ok(!gf.has(f), f);
  assert.ok(!fs.readFileSync(path.join(root, 'js/gf-main.js'), 'utf8').includes('tree-geodata.bin'));
  // the shared renderer and its materials are unchanged (CC-005b: tsl-materials.js gains only the opt-in footprintBase
  // option, 319df9cd... -> 534b8cff...; tests/gf-terrain.test.mjs checks undoing it gives back 319df9cd...)
  // CC-MOBILE: trees.js gains only the opt-in maxDist option (default MAX_DIST) and exports MAX_DIST, 7303a1d5... ->
  // the pin below; undoing exactly that gives back 7303a1d5...
  const trees = fs.readFileSync(path.join(root, 'js/trees.js'), 'utf8');
  assert.equal(sha('js/trees.js'), '1318d3385edad4474f648cbda83c0e8fb52b62493c6d47119eb3e496b462593d');
  const undone = trees
    .replace(" * Options: maxDist, the draw distance per tier (default MAX_DIST; a caller's lower-spec device tier may pass shorter).\n", '')
    .replace('function createTreeField(_scene, sites, colliders = [], { maxDist = MAX_DIST } = {}) {', 'function createTreeField(_scene, sites, colliders = []) {')
    .replace('const td = maxDist[tier[i]];', 'const td = MAX_DIST[tier[i]];')
    .replaceAll('= maxDist.map(', '= MAX_DIST.map(')
    .replace(', MAX_DIST as TREE_MAX_DIST };', ' };');
  assert.equal(createHash('sha256').update(undone).digest('hex'), '7303a1d5ccca950bf78a5fa69bef5c9d295a597f9806d2ff54d19ea38d5514f8');
  assert.equal(sha('js/tsl-materials.js'), '534b8cff86d76c7cb4fac1c5992190f4053c77d3563e8050143e3067304b1cf8');
});
