test('gf-trees.js is regenerated byte for byte; placement gives the same sites every time', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gf-trees '));
  try {
    const out = path.join(dir, 'gf-trees.js');
    const run = spawnSync(process.execPath, [path.join(root, 'tools/gf/build-gf-trees.mjs'), out], { encoding: 'utf8' });
    assert.ifError(run.error);
    assert.equal(run.status, 0, run.stderr + run.stdout);
    assert.ok(fs.readFileSync(out).equals(fs.readFileSync(path.join(root, 'js/gf-trees.js'))), 'js/gf-trees.js is stale');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  assert.equal(JSON.stringify(placeGfTrees(GF_TREES, { buildings: GF_BUILDINGS, geo: GF_GEO })), JSON.stringify(plan));
});

