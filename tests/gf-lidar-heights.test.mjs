test('bad data fails loudly', () => {
  assert.throws(() => buildGfLidarHeights(fixture((d) => { d.heights.w1 = [7.2, 'ok']; }), GF_BUILDINGS, 'x'), /unknown OSM id w1/);
  assert.throws(() => buildGfLidarHeights(fixture((d) => { d.heights.w87102351 = [7.2, 'shiny']; }), GF_BUILDINGS, 'x'), /w87102351: unknown flag "shiny"/);
  assert.throws(() => buildGfLidarHeights(fixture((d) => { d.heights.w87102351 = [75, 'ok']; }), GF_BUILDINGS, 'x'), /w87102351: usable height 75 m outside 2-60 m/);
  assert.throws(() => buildGfLidarHeights(fixture((d) => { d.heights.w87102351 = [Number.NaN, 'reviewed']; }), GF_BUILDINGS, 'x'), /usable height null m|usable height NaN/);
  assert.throws(() => buildGfLidarHeights(fixture((d) => { d.rules.use = ['ok']; }), GF_BUILDINGS, 'x'), /rules\.use is \["ok"\]/);
  assert.throws(() => buildGfLidarHeights(fixture((d) => { d.rules.use = ['ok', 'reviewed', 'mixed']; }), GF_BUILDINGS, 'x'), /rules\.use/);
  assert.throws(() => buildGfLidarHeights(fixture((d) => { d.meta.osm.osmBase = '2026-01-01T00:00:00Z'; }), GF_BUILDINGS, 'x'), /osmBase/);
  assert.throws(() => buildGfLidarHeights({ ...doc, rawKeys: ['w87102351', 'w87102351'] }, GF_BUILDINGS, 'x'), /duplicate key w87102351/);
  // a flagged value outside the range is fine: it is never applied
  assert.equal(buildGfLidarHeights(fixture((d) => { d.heights.w87102351 = [75, 'tall']; }), GF_BUILDINGS, 'x').heights.length, 7275);
});

