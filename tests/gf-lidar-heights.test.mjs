test('ranges and consistency: heights, colliders, storefronts, order', () => {
  const { records, colliders, obstacles } = createGfBuildingRecords(lidarCopy);
  for (const r of lidarCopy.buildings) if (r[at.src] === 4) assert.ok(r[at.height] >= 2.0 && r[at.height] <= 60, r[at.osm]);
  assert.equal(records.length, 7789);
  assert.equal(colliders.length, 7789);
  assert.equal(obstacles.length, 7789);
  records.forEach((r, i) => {
    assert.equal(r.osm, GF_BUILDINGS.buildings[i][at.osm]);
    assert.equal(colliders[i].maxY, r.height);
    if (r.storefronts) assert.ok(r.height >= 3.5, r.osm);
  });
});

