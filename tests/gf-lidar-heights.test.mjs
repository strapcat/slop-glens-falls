// Glens Falls building heights from USGS 3DEP LiDAR (CC-003b): js/gf-lidar-heights.js, generated by
// tools/gf/build-gf-lidar-heights.mjs from tools/gf/data/gf_lidar_heights.json, applied by js/gf-building-heights.js to
// a copy of GF_BUILDINGS (src 4) where CC-003 used its default rule

const root = fileURLToPath(new URL('../', import.meta.url));
const JSON_SHA = 'f4d7d4c786689440647d7d5ba343afe91bc8ed2b90ff42e2b1dc7ed96c342fbf';
const doc = JSON.parse(fs.readFileSync(path.join(root, 'tools/gf/data/gf_lidar_heights.json'), 'utf8'));
const at = Object.fromEntries(GF_BUILDINGS.fields.map((f, i) => [f, i]));
const sha = (f) => createHash('sha256').update(fs.readFileSync(path.join(root, f))).digest('hex');
const quiet = (fn) => {
  const info = console.info;
  console.info = () => {};
  try {
    return fn();
  } finally {
    console.info = info;
  }
};
const edgeHash = (net) => createHash('sha256')
  .update(JSON.stringify(net.edges.map((e) => [e.from.id, e.to.id, e.sx, e.sz, e.len, e.lanes, e.moves.map((m) => [m.to.id, m.out])])))
  .digest('hex');

const before = JSON.stringify(GF_BUILDINGS).length + ':' + createHash('sha256').update(JSON.stringify(GF_BUILDINGS)).digest('hex');
const lidarBefore = createHash('sha256').update(JSON.stringify(GF_LIDAR_HEIGHTS)).digest('hex');
const { data: lidarCopy, applied } = applyLidarHeights(GF_BUILDINGS, GF_LIDAR_HEIGHTS);
const original = new Map(GF_BUILDINGS.buildings.map((r) => [r[at.osm], r]));
const copyById = new Map(lidarCopy.buildings.map((r) => [r[at.osm], r]));
const usable = new Map(GF_LIDAR_HEIGHTS.heights);
const sources = (rows) => {
  const n = [0, 0, 0, 0, 0];
  for (const r of rows) n[r.src ?? r[at.src]]++;
  return n;
};

test('the LiDAR JSON is the one prepared for CC-003b, for the CC-003 OSM extract', () => {
  assert.equal(sha('tools/gf/data/gf_lidar_heights.json'), JSON_SHA);
  assert.equal(GF_LIDAR_HEIGHTS.sha256, JSON_SHA);
  assert.equal(doc.meta.osm.osmBase, GF_BUILDINGS.osmBase);
  assert.equal(doc.meta.osm.osmBase, '2026-11-01T13:05:10Z');
  assert.equal(doc.meta.osm.sha256, sha('tools/gf/data/osm_gf_buildings.json'));
  assert.equal(GF_LIDAR_HEIGHTS.srcCode, 4);
  assert.equal(GF_LIDAR_HEIGHTS.srcLabel, 'lidar 2022-23');
  assert.deepEqual(GF_LIDAR_HEIGHTS.collected, { start: '2022-11-08', end: '2023-04-15' });
  assert.match(GF_LIDAR_HEIGHTS.credit, /USGS 3D Elevation Program/);
});

test('gf-lidar-heights.js is regenerated byte for byte; applying it is deterministic and mutates nothing', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gf-lidar-heights '));
  try {
    const out = path.join(dir, 'gf-lidar-heights.js');
    const run = spawnSync(process.execPath, [path.join(root, 'tools/gf/build-gf-lidar-heights.mjs'), out], { encoding: 'utf8' });
    assert.ifError(run.error);
    assert.equal(run.status, 0, run.stderr + run.stdout);
    assert.ok(fs.readFileSync(out).equals(fs.readFileSync(path.join(root, 'js/gf-lidar-heights.js'))), 'js/gf-lidar-heights.js is stale');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  assert.equal(JSON.stringify(applyLidarHeights(GF_BUILDINGS, GF_LIDAR_HEIGHTS)), JSON.stringify({ data: lidarCopy, applied }));
  assert.equal(JSON.stringify(GF_BUILDINGS).length + ':' + createHash('sha256').update(JSON.stringify(GF_BUILDINGS)).digest('hex'), before);
  assert.equal(createHash('sha256').update(JSON.stringify(GF_LIDAR_HEIGHTS)).digest('hex'), lidarBefore);
  assert.equal(JSON.stringify(createGfBuildingRecords(lidarCopy)), JSON.stringify(createGfBuildingRecords(lidarCopy)));
  assert.notEqual(lidarCopy, GF_BUILDINGS);
  assert.deepEqual(Object.keys(lidarCopy), [...Object.keys(GF_BUILDINGS), 'lidar']);
  assert.equal(lidarCopy.fields, GF_BUILDINGS.fields);
});

test('counts: 7784 matched, the five unmatched, the flags, 7276 usable, sources [0, 49, 509, 0, 7231]', () => {
  assert.equal(Object.keys(doc.heights).length, 7784);
  assert.deepEqual(doc.unmatched.map((u) => u.osm), ['w696012135', 'w799190076', 'w817028882', 'w835350997', 'r11213302']);
  assert.equal(GF_LIDAR_HEIGHTS.counts.matched, 7784);
  assert.deepEqual(GF_LIDAR_HEIGHTS.counts.flags, { ok: 7271, reviewed: 5, sparse: 2, low: 17, ground: 30, mixed: 446, tall: 13, cap: 0 });
  assert.equal(GF_LIDAR_HEIGHTS.heights.length, 7276);
  assert.equal(GF_LIDAR_HEIGHTS.counts.usable, 7276);
  // in GF_BUILDINGS order
  const order = new Map(GF_BUILDINGS.buildings.map((r, i) => [r[at.osm], i]));
  for (let i = 1; i < GF_LIDAR_HEIGHTS.heights.length; i++) assert.ok(order.get(GF_LIDAR_HEIGHTS.heights[i - 1][0]) < order.get(GF_LIDAR_HEIGHTS.heights[i][0]));
  assert.deepEqual(sources(lidarCopy.buildings), [0, 49, 509, 0, 7231]);
  assert.deepEqual(applied.bySrc, { 0: 0, 1: 49, 2: 509, 4: 7231 });
  assert.equal(applied.lidar, 7231);
  assert.equal(applied.skippedOsm, 45);
  const share = applied.lidar / GF_BUILDINGS.buildings.length;
  assert.equal(share, 7231 / 7789);
  assert.ok(share >= 0.92);
});

test('precedence: OSM heights win, LiDAR replaces only the default rule, flagged values are not applied', () => {
  let osm = 0, lidar = 0, kept = 0;
  for (const r of lidarCopy.buildings) {
    const o = original.get(r[at.osm]);
    if (o[at.src] === 0 || o[at.src] === 1) {
      assert.equal(r, o, `${o[at.osm]}: an OSM height is never changed`);
      osm++;
    } else if (r[at.src] === 4) {
      assert.equal(r[at.height], usable.get(r[at.osm]), r[at.osm]);
      assert.deepEqual(r.filter((_, i) => i !== at.height && i !== at.src), o.filter((_, i) => i !== at.height && i !== at.src));
      lidar++;
    } else {
      assert.equal(r[at.src], 2);
      assert.equal(r, o);
      assert.ok(!usable.has(r[at.osm]), `${r[at.osm]} has a usable height but kept the default rule`);
      kept++;
    }
  }
  assert.deepEqual([osm, lidar, kept], [49, 7231, 509]);
  assert.deepEqual([copyById.get('w126823063')[at.height], copyById.get('w126823063')[at.src]], [33.6, 1], '333 Glen St');
  assert.deepEqual([copyById.get('w1131808794')[at.height], copyById.get('w1131808794')[at.src]], [36.9, 1], 'Stichman Towers');
  for (const [id, flag, h] of [['w817027795', 'low', 0.4], ['w1359097011', 'ground', 27.3], ['w1201107574', 'mixed', 30.4], ['w892098575', 'tall', 12.7]]) {
    assert.deepEqual(doc.heights[id], [h, flag], id);
    assert.ok(!usable.has(id), id);
    assert.equal(copyById.get(id), original.get(id), `${id} (${flag}) applied`);
    assert.equal(copyById.get(id)[at.src], 2);
  }
});

