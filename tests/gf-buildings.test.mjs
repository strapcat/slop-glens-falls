test('gf-buildings.js is regenerated byte for byte; the records build the same every time', () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gf-buildings '));
  try {
    const out = path.join(dir, 'gf-buildings.js');
    const result = spawnSync(process.execPath, [path.join(root, 'tools/gf/build-gf-buildings.mjs'), out], { encoding: 'utf8' });
    assert.ifError(result.error);
    assert.equal(result.status, 0, result.stderr + result.stdout);
    assert.ok(fs.readFileSync(out).equals(fs.readFileSync(path.join(root, 'js/gf-buildings.js'))), 'js/gf-buildings.js is stale');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
  assert.equal(JSON.stringify(createGfBuildingRecords(GF_BUILDINGS)), JSON.stringify({ records, colliders, obstacles }));
});

test('7789 buildings: 0 heights from a height tag, 49 from building:levels, 7740 from the default rule', () => {
  assert.equal(rows.length, 7789);
  const src = [0, 0, 0];
  for (const r of rows) src[r[at.src]]++;
  assert.deepEqual(src, [0, 49, 7740]);
  // ways by id, then relations by id
  const key = (r) => [r[at.osm][0] === 'w' ? 0 : 1, Number(r[at.osm].slice(1))];
  for (let i = 1; i < rows.length; i++) {
    const [ta, ia] = key(rows[i - 1]), [tb, ib] = key(rows[i]);
    assert.ok(ta < tb || (ta === tb && ia < ib), `${rows[i - 1][at.osm]} before ${rows[i][at.osm]}`);
  }
  const school = rows.find((r) => r[at.osm] === 'r11213302');
  assert.ok(school, 'the Oliver W Winch Middle School multipolygon');
  assert.equal(school[at.holes].length, 1);
  assert.equal(new Set(rows.map((r) => r[at.osm])).size, rows.length, 'one row per OSM object');
  assert.ok(!rows.some((r) => r[at.kind] === 'roof' || r[at.kind] === 'construction'));
});

// The default rule, written out again from the CC-003 spec (independently of the generator)
function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
function defaultHeight(id, kind, area) {
  const one = 'garage garages shed outbuilding carport greenhouse kiosk hut service supermarket industrial warehouse chapel'.split(' ');
  const two = 'house detached semidetached_house residential terrace commercial retail school church healthcare civic public'.split(' ');
  const three = 'apartments office hospital parking'.split(' ');
  if (area >= 2000 && !'school hospital apartments office parking church'.split(' ').includes(kind)) return 7.5;
  let levels = one.includes(kind) ? 1 : two.includes(kind) ? 2 : three.includes(kind) ? 3 : area < 40 ? 1 : 2;
  const r = mulberry32(id)();
  if (levels >= 2 && !['church', 'school', 'hospital'].includes(kind)) levels += r < 0.15 ? -1 : r >= 0.85 ? 1 : 0;
  return round1(levels * 3.3 + 0.6);
}

test('heights: tagged levels as tagged, every other height the documented approximation', () => {
  assert.match(GF_BUILDINGS.heightRule, /approximation/);
  assert.equal(GF_BUILDINGS.storey, 3.3);
  for (const r of rows) {
    const h = r[at.height];
    assert.ok(h >= 2.5 && h <= 60, `${r[at.osm]} ${h} m`);
    if (r[at.src] === 1) {
      const levels = parseFloat(String(r[at.levels]).match(/\d+(?:\.\d+)?/)[0]);
      assert.equal(h, round1(levels * 3.3 + 0.6), r[at.osm]);
    } else {
      assert.equal(r[at.src], 2, r[at.osm]);
      assert.equal(r[at.levels], null);
      const area = ringArea(r[at.outer]) - r[at.holes].reduce((s, hole) => s + ringArea(hole), 0);
      assert.equal(h, defaultHeight(Number(r[at.osm].slice(1)), r[at.kind], area), r[at.osm]);
    }
  }
});

test('footprints: finite, within 60 m of the bbox, outer rings of 3+ points and 1+ m²', () => {
  const { x0, x1, z0, z1 } = BBOX_M;
  for (const r of rows) {
    const outer = r[at.outer];
    assert.ok(outer.length >= 6 && ringArea(outer) >= 1, r[at.osm]);
    for (const ring of [outer, ...r[at.holes]]) {
      for (let i = 0; i < ring.length; i += 2) {
        const x = ring[i], z = ring[i + 1];
        assert.ok(Number.isFinite(x) && Number.isFinite(z) && x >= x0 - 60 && x <= x1 + 60 && z >= z0 - 60 && z <= z1 + 60, `${r[at.osm]} (${x}, ${z})`);
      }
    }
  }
});

test('records: styles, storefronts, colliders and obstacles in the controllers\' and road network\'s forms', () => {
  assert.equal(records.length, rows.length);
  assert.equal(colliders.length, rows.length);
  assert.equal(obstacles.length, rows.length);
  const count = (f) => records.filter(f).length;
  assert.equal(count((r) => r.style === 'brick') + count((r) => r.style === 'stone') + count((r) => r.style === 'clapboard'), rows.length);
  assert.ok(count((r) => r.style === 'stone') > 0 && count((r) => r.style === 'clapboard') > 0 && count((r) => r.storefronts) > 0);
  const school = records.find((r) => r.osm === 'r11213302');
  assert.equal(school.style, 'stone');
  for (let i = 0; i < records.length; i++) {
    const r = records[i], c = colliders[i], o = obstacles[i];
    assert.ok(Number.isInteger(r.seed) && r.seed >= 0 && r.seed < 1000 && r.tone >= 0 && r.tone < 1);
    assert.equal(c.minY, 0);
    assert.equal(c.maxY, r.height);
    assert.equal(c.polygon, r.polygons[0]);
    assert.equal(o.pedestrianOnly, true);
    assert.equal(o.polygon, r.polygons[0]);
    assert.equal(r.cx, (c.minX + c.maxX) / 2);
    if (r.storefronts) assert.ok(r.height >= 3.5);
  }
  // party-wall neighbours: a building's own record comes back (createBuildingFootprints skips it by its polygons)
  const near = neighboursFor(records);
  const downtown = records.find((r) => Math.hypot(r.cx + 200, r.cz + 150) < 150 && r.style === 'brick');
  const found = near(downtown);
  assert.ok(found.some((n) => n.polygons === downtown.polygons));
  assert.ok(found.every((n) => n.x0 < downtown.maxX + 2 && n.x1 > downtown.minX - 2 && n.z0 < downtown.maxZ + 2 && n.z1 > downtown.minZ - 2));
});

test('no drive-link centreline runs through a building', () => {
  const hits = [];
  let midpoints = 0, samples = 0;
  for (const l of driveLinks(GF_GEO)) {
    for (let k = 0; k + 1 < l.pts.length; k++) {
      const [ax, az] = l.pts[k], [bx, bz] = l.pts[k + 1];
      const b = buildingAt((ax + bx) / 2, (az + bz) / 2);
      midpoints++;
      if (b) hits.push(`${b.osm} ${l.name} midpoint`);
      const len = Math.hypot(bx - ax, bz - az);
      for (let s = 0; s < len; s += 5) {
        const hit = buildingAt(ax + ((bx - ax) * s) / len, az + ((bz - az) * s) / len);
        samples++;
        if (hit) hits.push(`${hit.osm} ${l.name} at ${s} m`);
      }
    }
  }
  assert.ok(midpoints > 2800 && samples > 30000, `${midpoints} midpoints, ${samples} samples`);
  assert.deepEqual(hits.filter((h) => !KNOWN_STRAYS.includes(h.split(' ')[0])), []);
});

const blocks = createGfBlocks(GF_GEO);
const lotsOnly = quiet(() => buildRoadNetwork([], blocks.lotObstacles, [], gfRoadSource(GF_GEO)));
const withBuildings = quiet(() => buildRoadNetwork([], [...blocks.lotObstacles, ...obstacles], [], gfRoadSource(GF_GEO)));

test('buildings are obstacles to pedestrians only: the car network is unchanged', () => {
  assert.equal(withBuildings.edges.length, 2498);
  assert.equal(edgeHash(withBuildings), edgeHash(lotsOnly));
});

test('sidewalk tracks with the buildings: over 2100 edges, none through a building, each on its own block', () => {
  const routes = createPedestrianRoutes({ walkable: withBuildings.walkable, onSidewalk: blocks.onSidewalk }, blocks.blockAt, { insets: [0.6, 1.2] });
  const all = withBuildings.edges.map((e) => routes.along(e));
  const withTracks = all.filter((t) => t.length).length;
  assert.ok(withTracks > 2100, `${withTracks} edges with tracks`);
  let n = 0;
  for (const list of all) {
    for (const t of list) {
      for (const f of [0, 0.25, 0.5, 0.75, 1]) {
        const x = t.ax + t.ux * t.len * f, z = t.az + t.uz * t.len * f;
        const b = buildingAt(x, z);
        assert.equal(b, null, `track through ${b && b.osm} at (${x.toFixed(1)}, ${z.toFixed(1)})`);
        if (f === 0 || f === 0.5 || f === 1) assert.equal(blocks.blockAt(x, z), t.block, 'track off its block');
      }
      n++;
    }
  }
  assert.ok(n > 4000, `${n} tracks`);
});
